/**
 * Grow the exercise catalog from 117 hand-curated entries to ~900, using
 * free-exercise-db (https://github.com/yuhonas/free-exercise-db, Unlicense / public domain).
 *
 * Adds the richer metadata the dataset carries (equipment, level, mechanic, force,
 * granular muscles, step-by-step instructions, a second photo) and bulk-inserts every
 * exercise. Notably this takes barbell 27 -> 179 and cable 14 -> 81.
 *
 * The curated 117 rows win on conflict: COALESCE keeps whatever they already have and
 * only fills columns that are still NULL, so existing images and categories are untouched
 * and no saved workout can break.
 *
 * Data file is generated by scripts/build-exercise-catalog.js and committed, so this
 * migration needs no network access.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const shorthands = undefined;

const DATA_FILE = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  'data/exercises-catalog.json',
);

export const up = (pgm) => {
  pgm.sql(`
    ALTER TABLE exercises
      ADD COLUMN IF NOT EXISTS equipment text,
      ADD COLUMN IF NOT EXISTS discipline text,
      ADD COLUMN IF NOT EXISTS level text,
      ADD COLUMN IF NOT EXISTS mechanic text,
      ADD COLUMN IF NOT EXISTS force text,
      ADD COLUMN IF NOT EXISTS primary_muscles text[],
      ADD COLUMN IF NOT EXISTS secondary_muscles text[],
      ADD COLUMN IF NOT EXISTS instructions text[],
      ADD COLUMN IF NOT EXISTS image_url_2 text;
  `);

  // The existing rows already store equipment in `category` ('barbell', 'cable', ...),
  // so seed the new dedicated column from it before importing.
  pgm.sql(`UPDATE exercises SET equipment = category WHERE equipment IS NULL AND category IS NOT NULL;`);

  const raw = fs.readFileSync(DATA_FILE, 'utf8').trim();
  // Dollar-quoting sidesteps escaping entirely (many names/instructions contain
  // apostrophes). Guard in case a future dataset ever contains the delimiter.
  const DELIM = '$exercise_catalog$';
  if (raw.includes(DELIM)) {
    throw new Error(`exercises-catalog.json contains the dollar-quote delimiter ${DELIM}`);
  }

  pgm.sql(`
    INSERT INTO exercises (
      name, muscle_group, category, equipment, discipline, level, mechanic, force,
      primary_muscles, secondary_muscles, instructions, image_url, image_url_2
    )
    SELECT
      x.name, x."muscleGroup", x.category, x.equipment, x.discipline, x.level, x.mechanic, x.force,
      x."primaryMuscles", x."secondaryMuscles", x.instructions, x."imageUrl", x."imageUrl2"
    FROM jsonb_to_recordset(${DELIM}${raw}${DELIM}::jsonb) AS x(
      name text,
      "muscleGroup" text,
      category text,
      equipment text,
      discipline text,
      level text,
      mechanic text,
      force text,
      "primaryMuscles" text[],
      "secondaryMuscles" text[],
      instructions text[],
      "imageUrl" text,
      "imageUrl2" text
    )
    ON CONFLICT (name) DO UPDATE SET
      muscle_group      = COALESCE(exercises.muscle_group, EXCLUDED.muscle_group),
      category          = COALESCE(exercises.category, EXCLUDED.category),
      equipment         = COALESCE(exercises.equipment, EXCLUDED.equipment),
      discipline        = COALESCE(exercises.discipline, EXCLUDED.discipline),
      level             = COALESCE(exercises.level, EXCLUDED.level),
      mechanic          = COALESCE(exercises.mechanic, EXCLUDED.mechanic),
      force             = COALESCE(exercises.force, EXCLUDED.force),
      primary_muscles   = COALESCE(exercises.primary_muscles, EXCLUDED.primary_muscles),
      secondary_muscles = COALESCE(exercises.secondary_muscles, EXCLUDED.secondary_muscles),
      instructions      = COALESCE(exercises.instructions, EXCLUDED.instructions),
      image_url         = COALESCE(exercises.image_url, EXCLUDED.image_url),
      image_url_2       = COALESCE(exercises.image_url_2, EXCLUDED.image_url_2),
      updated_at        = now();
  `);

  pgm.sql(`
    CREATE INDEX IF NOT EXISTS idx_exercises_equipment ON exercises (equipment);
    CREATE INDEX IF NOT EXISTS idx_exercises_discipline ON exercises (discipline);
  `);
};

export const down = () => {
  // Intentionally empty — removing seeded exercises could break user workout data,
  // matching the other exercise seed migrations.
};
